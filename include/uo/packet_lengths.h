inline bool PacketIsVariable(u8 cmd) {
    return (kPacketLength[cmd] & kPacketLengthVariable) != 0;
}

inline bool PacketIsKnown(u8 cmd) {
    return kPacketLength[cmd] != 0;
}

// Fixed length for cmd. Caller must have ensured !PacketIsVariable(cmd).
inline u16 PacketFixedLength(u8 cmd) {
    return kPacketLength[cmd];
}

