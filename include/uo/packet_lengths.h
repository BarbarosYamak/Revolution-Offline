// Packet length table — verbatim port of g_PacketLengthTable @ 0x5170A8
// in client_2.0.7.exe. Each entry is the wire length of a packet whose
// first byte is the command. Bit 0x8000 marks "variable length"; for
// those, the next 2 bytes on the wire (after the command byte) are a
// big-endian total length including the command byte.
//
// Mapped opcodes in the original table extend through 0xCC (Cliloc Msg
// Affix). Slots 0xCD..0xFF read uninitialized rodata in the original
// binary (no real packet uses them); we treat them as 0 = unknown so
// the new client rejects them deterministically.
//
// Sources verified against IDB:
//   - g_PacketLengthTable  @ 0x5170A8
//   - Packet_Dispatch      @ 0x42DD80 (length read: [3*cmd].size; .size = u16)

