Huffman::Huffman() : bitPos_(0) {
    Build();
}

int Huffman::NewNode() {
    Node n;
    n.child[0] = -1;
    n.child[1] = -1;
    n.value = -1;
    nodes_.push_back(n);
    return static_cast<int>(nodes_.size()) - 1;
}

void Huffman::Build() {
    nodes_.clear();
    NewNode();  // root at index 0

    for (int sym = 0; sym <= 256; ++sym) {
        const uint32_t bits = kEnc[sym * 2];
        const uint32_t code = kEnc[sym * 2 + 1];
        int node = 0;
        for (int i = static_cast<int>(bits) - 1; i >= 0; --i) {
            const int bit = (code >> i) & 1;
            if (nodes_[node].child[bit] < 0) {
                const int created = NewNode();  // may reallocate nodes_
                nodes_[node].child[bit] = created;
            }
            node = nodes_[node].child[bit];
        }
        nodes_[node].value = sym;
    }
}

void Huffman::Reset() {
    buf_.clear();
    bitPos_ = 0;
}

bool Huffman::Decompress(const u8* data, usize n, std::vector<u8>& out) {
    buf_.insert(buf_.end(), data, data + n);

    const usize totalBits = buf_.size() * 8;
    usize pos = bitPos_;

    for (;;) {
        int node = 0;
        usize p = pos;
        for (;;) {
            if (p >= totalBits) goto done;  // symbol runs past input
            const int bit = (buf_[p >> 3] >> (7 - (p & 7))) & 1;
            ++p;
            const int next = nodes_[node].child[bit];
            if (next < 0) return false;     // malformed code
            node = next;
            if (nodes_[node].value != -1) break;  // reached a leaf
        }

        const int val = nodes_[node].value;
        if (val == 256) {
            // Flush: drop the rest of the current byte, align to next byte.
            pos = (p + 7) & ~static_cast<usize>(7);
        } else {
            out.push_back(static_cast<u8>(val));
            pos = p;
        }
    }

done:
    const usize wholeBytes = pos >> 3;
    if (wholeBytes) buf_.erase(buf_.begin(), buf_.begin() + wholeBytes);
    bitPos_ = pos & 7;
    return true;
}

