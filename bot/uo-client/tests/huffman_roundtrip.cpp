static int HuffmanCompress(uint8_t* dst, const uint8_t* src, int len) {
    int i, entry, bitCount = 0, bitValue = 0, outLen = 0;
    for (i = 0; i < len; i++) {
        entry = src[i] * 2;
        bitCount += huffmanEncoding[entry];
        bitValue <<= huffmanEncoding[entry];
        bitValue |= huffmanEncoding[entry + 1];
        while (bitCount >= 8) { bitCount -= 8; dst[outLen++] = (bitValue >> bitCount) & 0xFF; }
    }
    entry = 256 * 2;
    bitCount += huffmanEncoding[entry];
    bitValue <<= huffmanEncoding[entry];
    bitValue |= huffmanEncoding[entry + 1];
    if (bitCount & 7) { bitValue <<= 8 - (bitCount & 7); bitCount += 8 - (bitCount & 7); }
    while (bitCount >= 8) { bitCount -= 8; dst[outLen++] = (bitValue >> bitCount) & 0xFF; }
    return outLen;
}

static int g_fail = 0;

static void check(const std::vector<uint8_t>& got,
                  const std::vector<uint8_t>& want, const char* name) {
    if (got == want) { std::printf("PASS %s (%zu bytes)\n", name, want.size()); return; }
    std::printf("FAIL %s: got %zu want %zu\n", name, got.size(), want.size());
    g_fail = 1;
}

int main() {
    // Build several "packets", compress each as its own flushed block, and
    // concatenate (exactly how the server queues multiple sends).
    std::vector<std::vector<uint8_t>> msgs;

    // 0xB9 features (fixed 3) + 0xA9-style char list header pattern.
    msgs.push_back({0xB9, 0x00, 0x03});
    { std::vector<uint8_t> a9(939, 0); a9[0]=0xA9; a9[1]=0x03; a9[2]=0xAB; a9[3]=0x01;
      a9[4]='c'; a9[5]='x'; a9[6]='c'; a9[7]='x'; msgs.push_back(a9); }
    // Random-ish payloads of varied sizes to exercise all symbols.
    for (int s = 1; s <= 600; s += 37) {
        std::vector<uint8_t> m(s);
        for (int k = 0; k < s; ++k) m[k] = (uint8_t)((k * 73 + s * 13 + 5) & 0xFF);
        msgs.push_back(m);
    }

    std::vector<uint8_t> plainAll, compAll;
    for (auto& m : msgs) {
        plainAll.insert(plainAll.end(), m.begin(), m.end());
        std::vector<uint8_t> c(m.size() * 2 + 16);
        int n = HuffmanCompress(c.data(), m.data(), (int)m.size());
        compAll.insert(compAll.end(), c.begin(), c.begin() + n);
    }

    // 1) Feed the whole compressed stream at once.
    {
        uo::net::Huffman h;
        std::vector<uint8_t> out;
        if (!h.Decompress(compAll.data(), compAll.size(), out))
            { std::printf("FAIL whole: malformed\n"); g_fail = 1; }
        check(out, plainAll, "whole-stream");
    }

    // 2) Feed 1 byte at a time (worst-case streaming / partial symbols).
    {
        uo::net::Huffman h;
        std::vector<uint8_t> out;
        for (size_t i = 0; i < compAll.size(); ++i)
            if (!h.Decompress(&compAll[i], 1, out))
                { std::printf("FAIL drip: malformed at %zu\n", i); g_fail = 1; break; }
        check(out, plainAll, "1-byte-chunks");
    }

    // 3) Feed in 7-byte chunks (odd boundary).
    {
        uo::net::Huffman h;
        std::vector<uint8_t> out;
        for (size_t i = 0; i < compAll.size(); i += 7) {
            size_t n = (i + 7 <= compAll.size()) ? 7 : compAll.size() - i;
            if (!h.Decompress(&compAll[i], n, out))
                { std::printf("FAIL 7b: malformed at %zu\n", i); g_fail = 1; break; }
        }
        check(out, plainAll, "7-byte-chunks");
    }

    std::printf(g_fail ? "\nRESULT: FAIL\n" : "\nRESULT: OK\n");
    return g_fail;
}
